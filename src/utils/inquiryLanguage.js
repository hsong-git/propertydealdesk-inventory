export function translateInquiry(language, text, values = {}) {
  const normalized = normalizeInquiryLanguage(language);
  const raw = String(text ?? "");
  const translated = normalized === "en" ? raw : INQUIRY_TRANSLATIONS[raw]?.[normalized === "ms" ? 0 : 1] ?? raw;
  return translated.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

const translatedValueKeys = new Set(["propertyType", "relationship", "propertyUsage", "pet", "furnishing", "tenancy", "tenancyPeriod", "depositAgreement", "purchaseTimeline", "purpose", "loan", "race", "country"]);
export function translateInquiryValue(language, key, value) {
  return translatedValueKeys.has(key) ? translateInquiry(language, value) : String(value);
}
